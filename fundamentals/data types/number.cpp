#include <iostream>
int main(){
    // working with cpp Number types
    //declaration of integer data type
    int age = 24;
    int year = 1997;

    // declaration of float data type
    float price = 10.9f;
    float decimal =  99.8f;

    // declaration of double data type
    double doub = 23.9575937;
    double pie = 43.857398487;

    //declaration of long double data type
    long double pi = 3.6583753764l;
    long double num = 2.56l;

    std::cout <<"integer whole number" << std::endl;
    std::cout << age << std::endl;
    std::cout << year << std::endl;
    std::cout <<"float, decimal point number" << std::endl;
    std::cout << price << std::endl;
    std::cout << decimal << std::endl;
    std::cout <<"double data type" << std::endl;
    std::cout << doub << std::endl;
    std::cout << pie << std::endl;
    std::cout <<"long double data type" << std::endl;
    std::cout << pi << std::endl;
    std::cout << num << std::endl;

    return 0;
}